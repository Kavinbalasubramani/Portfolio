export const getBrandMeta = (skillName = '') => {
  const norm = skillName.toLowerCase().replace(/[\s.-]/g, '');
  if (norm.includes('php')) {
    return {
      Icon: PhpIcon,
      color: 'text-indigo-400',
      badgeBg: 'bg-indigo-500/15 border-indigo-500/30',
      progress: 'from-indigo-500 to-violet-500',
    };
  }
  if (norm.includes('laravel')) {
    return {
      Icon: LaravelIcon,
      color: 'text-rose-400',
      badgeBg: 'bg-rose-500/15 border-rose-500/30',
      progress: 'from-rose-500 to-red-500',
    };
  }
  if (norm.includes('react')) {
    return {
      Icon: ReactIcon,
      color: 'text-cyan-400',
      badgeBg: 'bg-cyan-500/15 border-cyan-500/30',
      progress: 'from-cyan-400 to-blue-500',
    };
  }
  if (norm.includes('javascript') || norm === 'js') {
    return {
      Icon: JavaScriptIcon,
      color: 'text-amber-400',
      badgeBg: 'bg-amber-500/15 border-amber-500/30',
      progress: 'from-amber-400 to-yellow-500',
    };
  }
  if (norm.includes('html')) {
    return {
      Icon: HtmlIcon,
      color: 'text-orange-400',
      badgeBg: 'bg-orange-500/15 border-orange-500/30',
      progress: 'from-orange-500 to-amber-500',
    };
  }
  if (norm.includes('css')) {
    return {
      Icon: CssIcon,
      color: 'text-blue-400',
      badgeBg: 'bg-blue-500/15 border-blue-500/30',
      progress: 'from-blue-500 to-indigo-500',
    };
  }
  if (norm.includes('bootstrap')) {
    return {
      Icon: BootstrapIcon,
      color: 'text-purple-400',
      badgeBg: 'bg-purple-500/15 border-purple-500/30',
      progress: 'from-purple-500 to-pink-500',
    };
  }
  if (norm.includes('tailwind')) {
    return {
      Icon: TailwindIcon,
      color: 'text-teal-400',
      badgeBg: 'bg-teal-500/15 border-teal-500/30',
      progress: 'from-teal-400 to-cyan-500',
    };
  }
  if (norm.includes('mysql') || norm.includes('sql')) {
    return {
      Icon: MysqlIcon,
      color: 'text-sky-400',
      badgeBg: 'bg-sky-500/15 border-sky-500/30',
      progress: 'from-sky-500 to-blue-600',
    };
  }
  if (norm.includes('mongo')) {
    return {
      Icon: MongoIcon,
      color: 'text-emerald-400',
      badgeBg: 'bg-emerald-500/15 border-emerald-500/30',
      progress: 'from-emerald-400 to-green-600',
    };
  }
  if (norm.includes('github')) {
    return {
      Icon: Github,
      color: 'text-slate-200',
      badgeBg: 'bg-slate-700/30 border-slate-600/40',
      progress: 'from-slate-400 to-slate-200',
    };
  }
  if (norm.includes('git')) {
    return {
      Icon: GitIcon,
      color: 'text-orange-400',
      badgeBg: 'bg-orange-500/15 border-orange-500/30',
      progress: 'from-orange-500 to-red-500',
    };
  }
  if (norm.includes('figma')) {
    return {
      Icon: FigmaIcon,
      color: 'text-pink-400',
      badgeBg: 'bg-pink-500/15 border-pink-500/30',
      progress: 'from-pink-500 to-violet-500',
    };
  }
  if (norm.includes('node')) {
    return {
      Icon: NodeIcon,
      color: 'text-green-400',
      badgeBg: 'bg-green-500/15 border-green-500/30',
      progress: 'from-green-500 to-emerald-500',
    };
  }

  if (norm.includes('express')) {
    return {
      Icon: Server,
      color: 'text-sky-400',
      badgeBg: 'bg-sky-500/15 border-sky-500/30',
      progress: 'from-sky-400 to-cyan-500',
    };
  }
  if (norm.includes('rest') || norm.includes('api')) {
    return {
      Icon: ReactIcon,
      color: 'text-sky-400',
      badgeBg: 'bg-sky-500/15 border-sky-500/30',
      progress: 'from-sky-400 to-indigo-500',
    };
  }

  // Fallback
  return {
    Icon: ReactIcon,
    color: 'text-sky-400',
    badgeBg: 'bg-sky-500/15 border-sky-500/30',
    progress: 'from-sky-500 to-indigo-500',
  };
};
